export function validateApplicationResult<T>(command: string, value: unknown): T {
  const check = applicationChecks[command];
  if (check && !check(value))
    throw new TransactionError(
      "invalid_response",
      `The app received incomplete ${command.replace(/_/g, " ")} data. Retry loading it.`,
    );
  return value as T;
}
