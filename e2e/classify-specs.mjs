// node e2e/classify-specs.mjs [--check]
// Rebuilds e2e/spec-classification.json from the static audit: a spec whose source or helpers touch a shared desktop resource is
// exclusive (with the reasons). A clean scan preserves prior parallel approval; it cannot grant it.
// Reviewed exclusive rationales survive alongside current detected reasons. --check exits 1 when the file is out of date.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { auditSpec, discoverSpecs } from "./lib/specAudit.mjs";

const e2eDir = path.dirname(fileURLToPath(import.meta.url));
const file = path.join(e2eDir, "spec-classification.json");
let previous = {};
try { previous = JSON.parse(fs.readFileSync(file, "utf8")); } catch { /* first run */ }
const manual = Object.fromEntries(Object.entries(previous.exclusive ?? {})
  .filter(([, reason]) => String(reason).startsWith("reviewed:")));
const approvedParallel = new Set(previous.parallelSafe ?? []);
const parallelSafe = [], exclusive = {};
for (const name of discoverSpecs(e2eDir)) {
  const reasons = [...new Set(auditSpec(path.join(e2eDir, name)))];
  const detected = reasons.length ? "; detected: " + reasons.join("; ") : "";
  // A reviewed rationale is opaque owner text. Never parse away a clause as if it were our annotation.
  if (manual[name]) exclusive[name] = manual[name] + (detected && !manual[name].endsWith(detected) ? detected : "");
  else if (reasons.length) exclusive[name] = reasons.join("; ");
  else if (approvedParallel.has(name)) parallelSafe.push(name);
  else exclusive[name] = previous.exclusive?.[name] || "not reviewed for parallel execution; exclusive until approved";
}
const next = {
  note: "Generated by e2e/classify-specs.mjs from a static scan (see e2e/lib/specAudit.mjs). A spec in neither list is exclusive. Promote a spec to parallelSafe only with repeated parallel-run evidence; demote it on any contention failure. Hand-written exclusive reasons must begin with 'reviewed:'.",
  parallelSafe, exclusive,
};
const text = JSON.stringify(next, null, 2) + "\n";
if (process.argv.includes("--check")) {
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === text) { console.log("spec-classification.json is up to date."); process.exit(0); }
  console.error("spec-classification.json is out of date; run: node e2e/classify-specs.mjs"); process.exit(1);
}
fs.writeFileSync(file, text);
console.log(`${parallelSafe.length} parallel-safe, ${Object.keys(exclusive).length} exclusive -> ${file}`);
